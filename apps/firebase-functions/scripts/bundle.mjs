// Builds the deployable Cloud Functions artifact in ./deploy: one ESM entry
// (src/index.ts plus every @paldora/* workspace package) and a generated
// package.json that lists only the genuinely external runtime packages at the
// exact versions pinned in the workspace. `firebase deploy` uploads this
// directory alone and Cloud Build runs `npm install` in it, so it must not
// contain `workspace:` specifiers. Local file work only.
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(here, '..');
const repoRoot = resolve(appDir, '../..');
const outDir = join(appDir, 'deploy');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const appPackage = readJson(join(appDir, 'package.json'));

/** Workspace packages bundled into the entry; their deps become external deps. */
const BUNDLED_WORKSPACE = [
  'apps/firebase-functions',
  'packages/firebase-trusted',
  'packages/validation',
  'packages/domain',
  'packages/personalization',
];

const builtins = new Set(builtinModules);

/**
 * Packages kept out of the bundle: the Functions runtime pair that the CLI
 * and platform expect to resolve from node_modules, and sharp, which loads
 * platform-specific native binaries. Everything else (pure JavaScript such as
 * zod, parse5 and postcss) is bundled.
 */
const EXTERNAL_PACKAGES = new Set([
  'firebase-admin',
  'firebase-functions',
  'sharp',
]);

export function packageNameOf(specifier) {
  const parts = specifier.split('/');
  return specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

const externalizeBareImports = {
  name: 'externalize-bare-imports',
  setup(b) {
    b.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith('node:') || builtins.has(args.path))
        return { external: true };
      return EXTERNAL_PACKAGES.has(packageNameOf(args.path))
        ? { external: true }
        : undefined;
    });
  },
};

// Keep an installed node_modules between runs; everything generated is replaced.
mkdirSync(outDir, { recursive: true });
for (const name of ['index.js', 'package.json', 'package-lock.json'])
  rmSync(join(outDir, name), { force: true });

const result = await build({
  entryPoints: [join(appDir, 'src/index.ts')],
  outfile: join(outDir, 'index.js'),
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  metafile: true,
  legalComments: 'none',
  logLevel: 'warning',
  // Lets bundled CommonJS code call require() for builtins inside an ES module.
  banner: {
    js: "import { createRequire as __paldoraCreateRequire } from 'node:module'; const require = __paldoraCreateRequire(import.meta.url);",
  },
  plugins: [externalizeBareImports],
});

// Version table: exact versions declared by the bundled workspace packages.
const declared = new Map();
for (const dir of BUNDLED_WORKSPACE) {
  const pkg = readJson(join(repoRoot, dir, 'package.json'));
  for (const [name, version] of Object.entries(pkg.dependencies ?? {})) {
    if (version.startsWith('workspace:')) continue;
    const previous = declared.get(name);
    if (previous && previous !== version)
      throw new Error(`${name} is pinned to both ${previous} and ${version}`);
    declared.set(name, version);
  }
}

const externals = new Set();
for (const output of Object.values(result.metafile.outputs))
  for (const imported of output.imports)
    if (imported.external && !imported.path.startsWith('node:'))
      if (!builtins.has(imported.path))
        externals.add(packageNameOf(imported.path));

const dependencies = {};
for (const name of [...externals].sort()) {
  const version = declared.get(name);
  if (!version || !/^\d+\.\d+\.\d+$/.test(version))
    throw new Error(
      `external ${name} has no exact version in a bundled workspace package (found ${version})`,
    );
  dependencies[name] = version;
}
for (const required of ['firebase-admin', 'firebase-functions'])
  if (!dependencies[required])
    throw new Error(`${required} must remain an external dependency`);

writeFileSync(
  join(outDir, 'package.json'),
  `${JSON.stringify(
    {
      name: 'paldora-functions-deploy',
      version: '0.0.0',
      private: true,
      description:
        'Generated by apps/firebase-functions/scripts/bundle.mjs. Do not edit.',
      type: 'module',
      main: 'index.js',
      engines: { node: appPackage.engines.node },
      dependencies,
    },
    null,
    2,
  )}\n`,
);

// `firebase deploy` runs function discovery locally through
// deploy/node_modules/.bin/firebase-functions, so the deploy directory needs
// its own install. This also writes package-lock.json, which Cloud Build then
// honours (npm ci) so hosted installs match this one.
if (process.argv.includes('--install')) {
  const install = spawnSync(
    'npm',
    ['install', '--omit=dev', '--no-audit', '--no-fund', '--ignore-scripts'],
    { cwd: outDir, stdio: 'inherit' },
  );
  if (install.status !== 0) throw new Error('npm install in deploy/ failed');
}

process.stdout.write(
  `Bundled functions to ${outDir} (externals: ${Object.keys(dependencies).join(', ')})\n`,
);
